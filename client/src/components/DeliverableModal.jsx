import React from 'react';
import { X, CheckCircle, FileText, Copy, Download, Printer } from 'lucide-react';
import toast from 'react-hot-toast';

export default function DeliverableModal({ deal, isOpen, onClose }) {
  if (!isOpen || !deal) return null;

  const deliverable = deal.deliverable || {};

  const handleCopy = () => {
    navigator.clipboard.writeText(JSON.stringify(deliverable, null, 2));
    toast.success('Deliverable JSON copied to clipboard');
  };

  const handleDownloadMarkdown = () => {
    let md = `# Deliverable: ${deliverable.title || 'Completed Service Deliverable'}\n\n`;
    md += `**Service Type:** ${deal.serviceType}\n`;
    md += `**Provider Agent:** ${deal.sellerAgent}\n`;
    md += `**Agreed Amount:** $${deal.agreedAmount?.toFixed(2)} USD\n`;
    md += `**PayPal Order ID:** ${deal.paypalOrderId || 'N/A'}\n`;
    md += `**Date:** ${new Date(deal.createdAt).toLocaleDateString()}\n`;
    md += `**Settlement Status:** Verified & Settled via SpendMesh AI\n\n`;
    md += `---\n\n`;

    if (deliverable.summary) {
      md += `## Executive Summary\n${deliverable.summary}\n\n`;
    }

    if (Array.isArray(deliverable.slides)) {
      md += `## Presentation Slides (${deliverable.slides.length})\n\n`;
      deliverable.slides.forEach((s, idx) => {
        md += `### Slide ${idx + 1}: ${s.title || s.headline}\n`;
        md += `${s.content || (Array.isArray(s.bulletPoints) ? '* ' + s.bulletPoints.join('\n* ') : '') || ''}\n\n`;
      });
    }

    if (Array.isArray(deliverable.competitors)) {
      md += `## Competitive Intelligence Report (${deliverable.competitors.length})\n\n`;
      deliverable.competitors.forEach((c, idx) => {
        md += `### ${idx + 1}. ${c.name || 'Competitor'}\n`;
        md += `${c.strengths || c.details || JSON.stringify(c, null, 2)}\n\n`;
      });
    }

    if (!deliverable.slides && !deliverable.competitors) {
      md += `## Deliverable Payload\n\`\`\`json\n${JSON.stringify(deliverable, null, 2)}\n\`\`\`\n\n`;
    }

    md += `---\n*Generated by Autonomous Agent Network under SpendMesh AI Financial Escrow*\n`;

    const blob = new Blob([md], { type: 'text/markdown;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `${deal.serviceType || 'agent'}_deliverable_${deal.dealId ? deal.dealId.substring(0, 8) : 'deal'}.md`;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
    toast.success('Deliverable exported as Markdown (.md)');
  };

  const handlePrint = () => {
    window.print();
  };

  return (
    <div className="fixed inset-0 z-[70] overflow-y-auto bg-slate-900/40 backdrop-blur-xs flex items-center justify-center p-4 sm:p-6 print:static print:inset-auto print:block print:p-0 print:bg-white print:overflow-visible">
      <div className="bg-[#FFFFFF] rounded-xl shadow-2xl max-w-2xl w-full max-h-[88vh] flex flex-col border border-[#E6E8EC] overflow-hidden animate-in fade-in zoom-in-95 duration-150 my-auto print:shadow-none print:border print:border-[#E2E8F0] print:max-h-none print:block print:w-full print:max-w-none print:my-0">
        {/* Header */}
        <div className="flex items-center justify-between px-6 py-4 border-b border-[#E2E8F0] shrink-0 bg-white">
          <div className="flex items-center gap-3">
            <div className="w-9 h-9 rounded-lg bg-[#EFF4FF] text-[#2563EB] flex items-center justify-center border border-[#BFDBFE]">
              <FileText className="w-5 h-5 stroke-[2]" />
            </div>
            <div>
              <h3 className="text-[18px] font-bold text-[#101828]">
                Delivered AI Artifact
              </h3>
              <p className="text-[13px] text-[#475467]">
                Service: <span className="capitalize font-semibold text-[#101828]">{deal.serviceType}</span> &bull; Provider: <strong className="text-[#101828]">{deal.sellerAgent}</strong>
              </p>
            </div>
          </div>
          <button
            onClick={onClose}
            className="p-1.5 text-[#64748B] hover:text-[#101828] hover:bg-[#F8FAFC] rounded-lg transition-colors"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Content */}
        <div className="p-6 overflow-y-auto space-y-4 text-[14px]">
          {/* Payment Verification Callout */}
          <div className="bg-[#F0FDF4] border border-[#BBF7D0] rounded-xl p-3.5 flex items-center justify-between shadow-2xs">
            <div className="flex items-center gap-2 text-[#15803D] text-[13px] font-semibold">
              <CheckCircle className="w-4 h-4" />
              <span>Gated by verified PayPal Sandbox settlement</span>
            </div>
            <span className="text-[13px] text-[#15803D] font-mono font-bold tabular-nums">
              ${deal.agreedAmount?.toFixed(2)} USD
            </span>
          </div>

          <div>
            <h4 className="text-[16px] font-bold text-[#101828] mb-1.5">
              {deliverable.title || 'Completed Service Deliverable'}
            </h4>
            {deliverable.summary && (
              <p className="text-[14px] text-[#344054] bg-[#F8FAFC] p-4 rounded-xl border border-[#E2E8F0] leading-relaxed">
                {deliverable.summary}
              </p>
            )}
          </div>

          {/* Render structured slides */}
          {Array.isArray(deliverable.slides) && (
            <div className="space-y-2.5">
              <h5 className="text-[12px] font-bold text-[#475467] uppercase tracking-wider">
                Generated Slides ({deliverable.slides.length})
              </h5>
              <div className="space-y-2.5 max-h-64 overflow-y-auto pr-1">
                {deliverable.slides.map((s, idx) => (
                  <div key={idx} className="p-3.5 bg-[#F8FAFC] rounded-xl border border-[#E2E8F0]">
                    <span className="font-bold text-[#2563EB] text-[13px] block mb-1">
                      Slide {idx + 1}: {s.title || s.headline}
                    </span>
                    <p className="text-[13px] text-[#475467] leading-relaxed">
                      {s.content || s.bulletPoints?.join(', ')}
                    </p>
                  </div>
                ))}
              </div>
            </div>
          )}

          {/* Render structured competitor intelligence */}
          {Array.isArray(deliverable.competitors) && (
            <div className="space-y-2.5">
              <h5 className="text-[12px] font-bold text-[#475467] uppercase tracking-wider">
                Competitor Intelligence ({deliverable.competitors.length})
              </h5>
              <div className="grid grid-cols-1 sm:grid-cols-2 gap-3 max-h-64 overflow-y-auto">
                {deliverable.competitors.map((c, idx) => (
                  <div key={idx} className="p-3.5 bg-[#F8FAFC] rounded-xl border border-[#E2E8F0]">
                    <span className="font-bold text-[#101828] text-[13px] block">
                      {c.name || `Competitor ${idx + 1}`}
                    </span>
                    <p className="text-[#475467] text-[12px] mt-1 leading-relaxed">
                      {c.strengths || c.details || JSON.stringify(c)}
                    </p>
                  </div>
                ))}
              </div>
            </div>
          )}

          {/* Fallback code payload if raw json */}
          {!deliverable.slides && !deliverable.competitors && (
            <div className="bg-[#F8FAFC] text-[#101828] p-3.5 rounded-xl border border-[#E2E8F0] text-[12px] font-mono overflow-x-auto max-h-64 leading-relaxed">
              <pre>{JSON.stringify(deliverable, null, 2)}</pre>
            </div>
          )}
        </div>

        {/* Footer with One-Click Export & Print Actions */}
        <div className="px-6 py-3.5 bg-[#F8FAFC] border-t border-[#E2E8F0] flex flex-wrap items-center justify-between gap-3 rounded-b-xl shrink-0 print:hidden">
          <div className="flex flex-wrap items-center gap-2">
            <button
              onClick={handleDownloadMarkdown}
              className="px-3.5 py-2 text-[13px] font-semibold text-[#15803D] hover:text-[#166534] bg-[#F0FDF4] hover:bg-[#DCFCE7] border border-[#BBF7D0] rounded-lg flex items-center gap-2 transition-colors shadow-2xs"
              title="Download clean Markdown document"
            >
              <Download className="w-4 h-4 text-[#15803D]" />
              <span>Export Document (.md)</span>
            </button>
            <button
              onClick={handlePrint}
              className="px-3 py-2 text-[13px] font-semibold text-[#344054] hover:text-[#101828] bg-[#FFFFFF] border border-[#D0D5DD] rounded-lg hover:bg-[#F8FAFC] flex items-center gap-1.5 transition-colors shadow-2xs"
              title="Print document or save as PDF"
            >
              <Printer className="w-4 h-4 text-[#475467]" />
              <span>Print / PDF</span>
            </button>
            <button
              onClick={handleCopy}
              className="px-3 py-2 text-[13px] font-semibold text-[#344054] hover:text-[#101828] bg-[#FFFFFF] border border-[#D0D5DD] rounded-lg hover:bg-[#F8FAFC] flex items-center gap-1.5 transition-colors shadow-2xs"
            >
              <Copy className="w-4 h-4 text-[#475467]" />
              <span>Copy JSON</span>
            </button>
          </div>

          <button
            onClick={onClose}
            className="px-5 py-2 text-[13px] font-semibold text-white bg-[#2563EB] hover:bg-[#1D4ED8] rounded-lg transition-colors shadow-xs"
          >
            Done
          </button>
        </div>
      </div>
    </div>
  );
}
